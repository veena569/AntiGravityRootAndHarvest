export const ALL_INDIAN_STATES = INDIA_STATES_CITIES.map((s) => s.state);

export function getCitiesForState(stateName: string): string[] {
  if (!stateName) return [];
  const normalized = stateName.toLowerCase().trim();
  const match = INDIA_STATES_CITIES.find(
    (s) => s.state.toLowerCase() === normalized || normalized.includes(s.state.toLowerCase()) || s.state.toLowerCase().includes(normalized)
  );
  return match ? match.cities : [];
}
